# R/03_optical_model.R
# Bio-optical Model for Diffuse Attenuation Coefficient and Euphotic Depth

calculate_optical_depths <- function(par, chl, aph_443, adg_443, bbp_443, bbp_s) {
  wv <- seq(400, 700, by = 10)
  nw <- length(wv)
  ngrid <- length(chl)
  
  aw <- c(0.00663, 0.00473, 0.00454, 0.00495, 0.00635, 0.00922, 0.00979, 0.0106, 0.0127, 
          0.015, 0.0204, 0.0325, 0.0409, 0.0434, 0.0474, 0.0565, 0.0619, 0.0695, 
          0.0896, 0.1351, 0.2224, 0.2644, 0.2755, 0.2916, 0.3108, 0.34, 0.41, 0.439, 0.465, 
          0.516, 0.624)
  
  a_bricaud <- c(0.0241, 0.0287, 0.0328, 0.0359, 0.0378, 0.0350, 0.0328, 0.0309, 0.0281,
                 0.0254, 0.0210, 0.0162, 0.0126, 0.0103, 0.0085, 0.0070, 0.0057, 0.0050, 
                 0.0051, 0.0054, 0.0052, 0.0055, 0.0061, 0.0066, 0.0071, 0.0078, 0.0108, 
                 0.0174, 0.0161, 0.0069, 0.0025)
  
  e_bricaud <- c(0.6877, 0.6834, 0.6664, 0.6478, 0.6266, 0.5993, 0.5961, 0.5970, 0.5890, 
                 0.6074, 0.6529, 0.7212, 0.7939, 0.8500, 0.9036, 0.9312, 0.9345, 0.9298, 
                 0.8933, 0.8589, 0.8410, 0.8548, 0.8704, 0.8638, 0.8524, 0.8155, 0.8233, 
                 0.8138, 0.8284, 0.9255, 1.0286)
  
  kdpar <- numeric(ngrid)
  zeu   <- numeric(ngrid)
  
  for (g in seq_len(ngrid)) {
    aphi <- aph_443[g] * a_bricaud * (chl[g]^e_bricaud) / (0.03711 * (chl[g]^0.61479))
    a <- aw + aphi + adg_443[g] * exp(-0.018 * (wv - 443))
    bb <- bbp_443[g] * ((443 / wv)^bbp_s[g])
    
    kd <- a + 4.18 * (1 - 0.52 * exp(-10.8 * a)) * bb
    kdpar[g] <- 0.0665 + 0.874 * kd[10] - 0.00121 / kd[10]
    zeu[g] <- -log(0.1 / (par[g] * 0.95)) / kdpar[g]
  }
  
  list(kdpar = kdpar, zeu = zeu)
}